.MODEL SMALL
.STACK 100H
.DATA
	TRUE_MSG DB ' THE CONDITION IS TRUE$'
	FALSE_MSG DB ' THE CONDITION IS FALSE$'
.CODE
MAIN PROC
	MOV AX,@DATA
	MOV DS,AX
	
	MOV AH,1 
	INT 21H
	;AL= D
	CMP AL,'A'
	JNGE END_IF ; JL END_IF
	
	CMP AL,'Z'
	JNLE END_IF ; JG END_IF
	
	LEA DX,TRUE_MSG
	MOV AH,09H
	INT 21H
	
	JMP END_PGM
END_IF:
	LEA DX,FALSE_MSG
	MOV AH,09H
	INT 21H
	
	MOV AH,4CH
	INT 21H
MAIN ENDP
END MAIN	