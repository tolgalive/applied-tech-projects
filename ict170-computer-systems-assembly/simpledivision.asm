.MODEL SMALL
.STACK 100H
.DATA
	NUM1 DB 20
	NUM2 DB 4
	RESULT DB ?
	REMAINDER DB ?
	MSG1 DB 'THE RESULT IS : $'
	MSG2 DB 'THE REMAINDER IS : $'
.CODE
MAIN PROC
	MOV AX,@DATA
	MOV DS,AX
	
	MOV AL, NUM1
	MOV BL, NUM2
	
	MOV AH,0  ; XOR AH,AH
	DIV BL ; AX/BL AX = AH AL =  NUM1/NUM2
	
	
	
	MOV RESULT,AL ; RESULT = 5
	MOV REMAINDER,AH ; REMINDER = 0
	
	LEA DX,MSG1
	MOV AH,09H
	INT 21H
	
	
	ADD RESULT,48
	MOV DL,RESULT
	MOV AH,02H
	INT 21H
	
	
	
	MOV AH,4CH
	INT 21H
MAIN ENDP
END MAIN	