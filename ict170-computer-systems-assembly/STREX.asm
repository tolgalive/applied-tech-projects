.MODEL SMALL
.STACK 100H
.DATA
	STRING DB 'TOLGA$'
.CODE
MAIN PROC
	MOV AX,@DATA
	MOV DS,AX
	
	MOV CX,6
	XOR BX,BX
NEXT :
	MOV AL,STRING[BX] ; STRING[1] = C = AL AH
	PUSH AX
	INC BX ; I C T 1 7 0 
	LOOP NEXT
	
	MOV CX,6
	XOR BX,BX
NEXT1 :	
	POP AX
	MOV STRING[BX],AL ; 0 7 1 T C I $
	INC BX
	LOOP NEXT1
	
	MOV STRING[BX],'$'
	
	LEA DX,STRING
	MOV AH,09H
	INT 21H
	


	MOV AH,4CH
	INT 21H
MAIN ENDP
END MAIN	